"""Export the controller-free apple scene from SuperDex assets to MuJoCo MJCF.

This is a scene-only transformation. It does not add actuators or controllers.
The generated output is deterministic from repository-local SuperDex payloads.
"""

from __future__ import annotations

import json
import os
import shutil
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np
from scipy.spatial.transform import Rotation
from superdex import physics, robotics

from unisim.backend.superdex.materialization import rotation_matrix

ROOT = Path(__file__).resolve().parent.parent
REPO = ROOT.parents[1]
OUT = ROOT / "mujoco"
ROBOT = ROOT / "superdex/assets/robot/openarm_v20_wuji_trimmed.superdex_bot"
OBJECTS = ROOT / "superdex/assets/objects/objects.mochi_prefab"


def fmt(values) -> str:
    return " ".join(f"{float(value):.17g}" for value in values)


def xyzw_to_wxyz(value) -> np.ndarray:
    quat = np.asarray(value, dtype=float)
    quat = quat / np.linalg.norm(quat)
    return quat[[3, 0, 1, 2]]


def matrix_to_wxyz(rotation: np.ndarray) -> np.ndarray:
    if np.linalg.det(rotation) < 0:
        raise ValueError("rotation matrix is left-handed")
    quat = Rotation.from_matrix(rotation).as_quat()
    return quat[[3, 0, 1, 2]]


def upper_triangle_to_matrix(value) -> np.ndarray:
    upper = np.asarray(value, dtype=float)
    return np.array(
        [
            [upper[0], upper[1], upper[2]],
            [upper[1], upper[3], upper[4]],
            [upper[2], upper[4], upper[5]],
        ]
    )


def principal_inertia(inertia: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    eigenvalues, eigenvectors = np.linalg.eigh(inertia)
    if np.any(eigenvalues <= 0):
        raise ValueError(f"inertia is not positive definite: {eigenvalues}")
    if np.linalg.det(eigenvectors) < 0:
        eigenvectors[:, 0] *= -1
    if not np.allclose(
        eigenvectors @ np.diag(eigenvalues) @ eigenvectors.T, inertia, atol=1e-12, rtol=1e-12
    ):
        raise ValueError("principal-axis decomposition did not reproduce source inertia")
    return eigenvalues, eigenvectors


def write_obj(path: Path, vertices: np.ndarray, faces: np.ndarray) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="ascii") as output:
        output.write("# Generated by benchmark/pick_up_apple/mujoco_src/export.py\n")
        for vertex in vertices:
            output.write(f"v {fmt(vertex)}\n")
        for face in faces:
            output.write("f " + " ".join(str(int(index) + 1) for index in face) + "\n")


def mesh_arrays(shape) -> tuple[np.ndarray, np.ndarray]:
    mesh = physics.get_shape_mesh(shape)
    vertices = np.asarray(mesh.coordinates, dtype=float).reshape(-1, 3)
    faces = np.asarray(mesh.connectivity, dtype=np.int32).reshape(-1, 3)
    return vertices, faces


def export_mesh(shape, exported: dict[str, str], name: str) -> str:
    if name not in exported:
        vertices, faces = mesh_arrays(shape)
        relative = Path("meshes") / f"{name}.obj"
        write_obj(OUT / relative, vertices, faces)
        exported[name] = relative.as_posix()
    return exported[name]


def export_obj_asset(source: Path, exported: dict[str, str], name: str) -> str:
    if name not in exported:
        relative = Path("meshes") / f"{name}.obj"
        shutil.copyfile(source, OUT / relative)
        exported[name] = relative.as_posix()
    return exported[name]


def materialize_robot(directory: Path) -> Path:
    directory.mkdir(parents=True, exist_ok=True)
    (directory / ".superdex_root").touch()
    bundle = (REPO / "assets/superdex/bots").resolve()
    for name in ("arms", "hands"):
        (directory / name).symlink_to(bundle / name, target_is_directory=True)
    for source in ROBOT.parent.iterdir():
        if source != ROBOT:
            (directory / source.name).symlink_to(source)
    path = directory / ROBOT.name
    path.write_text(json.dumps(json.loads(ROBOT.read_text())))
    return path


def transform(joint, link) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    joint_position = np.asarray(joint.parent_link_from_joint.translation, dtype=float)
    joint_rotation = np.asarray(joint.parent_link_from_joint.rotation, dtype=float)
    link_position = np.asarray(link.parent_joint_from_link.translation, dtype=float)
    link_rotation = np.asarray(link.parent_joint_from_link.rotation, dtype=float)
    joint_quat = xyzw_to_wxyz(joint_rotation)
    rotation = rotation_matrix(joint_quat)
    body_position = joint_position + rotation @ link_position
    body_rotation = rotation @ rotation_matrix(xyzw_to_wxyz(link_rotation))
    return (
        joint_position,
        joint_quat,
        body_position,
        matrix_to_wxyz(body_rotation),
        rotation,
    )


def body_pose(joint, link) -> tuple[np.ndarray, np.ndarray]:
    _, _, position, quat, _ = transform(joint, link)
    return position, quat


def compose_pose(
    parent_position: np.ndarray,
    parent_quat: np.ndarray,
    child_position: np.ndarray,
    child_quat: np.ndarray,
) -> tuple[np.ndarray, np.ndarray]:
    parent_rotation = rotation_matrix(parent_quat)
    child_rotation = rotation_matrix(child_quat)
    return (
        parent_position + parent_rotation @ child_position,
        matrix_to_wxyz(parent_rotation @ child_rotation),
    )


def add_inertial(body: ET.Element, link) -> None:
    if link.mass is None or float(link.mass) <= 0:
        return
    inertia = upper_triangle_to_matrix(link.moment_of_inertia)
    eigenvalues, eigenvectors = principal_inertia(inertia)
    # MuJoCo reconstructs I = quat * diag(diaginertia) * quat^T.
    quat = matrix_to_wxyz(eigenvectors)
    attributes = {
        "pos": fmt(np.asarray(link.center_of_mass, dtype=float)),
        "mass": fmt([float(link.mass)]),
        "diaginertia": fmt(eigenvalues),
    }
    if not np.allclose(quat, [1, 0, 0, 0]):
        attributes["quat"] = fmt(quat)
    ET.SubElement(body, "inertial", attributes)


def add_robot_link(
    parent: ET.Element,
    link,
    joint,
    children: dict[int, list[int]],
    links: list,
    joints: list,
    exported: dict[str, str],
    pose_override: tuple[np.ndarray, np.ndarray] | None = None,
) -> None:
    position, quat = pose_override if pose_override is not None else body_pose(joint, link)
    attributes = {"name": str(link.name), "pos": fmt(position)}
    if not np.allclose(quat, [1, 0, 0, 0]):
        attributes["quat"] = fmt(quat)
    body = ET.SubElement(parent, "body", attributes)
    joint_type = str(joint.type)
    if joint_type.endswith("REVOLUTE"):
        axis = np.asarray(joint.axis, dtype=float)
        axis = axis / np.linalg.norm(axis)
        lower = float(np.dot(np.asarray(joint.min_limit, dtype=float), axis))
        upper = float(np.dot(np.asarray(joint.max_limit, dtype=float), axis))
        ET.SubElement(
            body,
            "joint",
            name=str(joint.name),
            type="hinge",
            axis=fmt(axis),
            range=fmt([lower, upper]),
            damping="0",
        )
    elif not joint_type.endswith("HARD"):
        raise NotImplementedError(f"robot joint {joint.name}: {joint.type}")
    add_inertial(body, link)
    if link.shape_file:
        shape = physics.load_shape_from_file(str(Path(link.shape_file).resolve()))
        export_mesh(shape, exported, str(link.name))
        ET.SubElement(
            body,
            "geom",
            name=f"{link.name}_collision",
            type="mesh",
            mesh=str(link.name),
        )
    for child in children[links.index(link)]:
        add_robot_link(body, links[child], joints[child], children, links, joints, exported)


def mesh_inertia(
    vertices: np.ndarray, faces: np.ndarray, mass: float
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    import trimesh

    mesh = trimesh.Trimesh(vertices=vertices, faces=faces, process=False)
    if not mesh.is_watertight or not mesh.is_volume:
        raise ValueError("apple collision mesh must be watertight")
    inertia = mass * np.asarray(mesh.moment_inertia, dtype=float) / float(mesh.volume)
    com = np.asarray(mesh.center_mass, dtype=float)
    eigenvalues, eigenvectors = principal_inertia(inertia)
    return com, eigenvalues, matrix_to_wxyz(eigenvectors)


def add_contact_exclusions(root: ET.Element, prefab) -> None:
    if not prefab.contact_overrides:
        return
    contact = ET.SubElement(root, "contact")
    for override in prefab.contact_overrides:
        if not bool(override.enable):
            ET.SubElement(
                contact,
                "exclude",
                name=f"exclude_{override.link_a}_{override.link_b}",
                body1=str(override.link_a),
                body2=str(override.link_b),
            )


def main() -> None:
    os.environ.setdefault("SUPERDEX_PRECISION", "fp64")
    physics.initialize(1)
    if OUT.exists():
        shutil.rmtree(OUT)
    (OUT / "meshes").mkdir(parents=True)
    exported: dict[str, str] = {}
    with tempfile.TemporaryDirectory(prefix="apple-mjcf-") as temporary:
        robot = materialize_robot(Path(temporary))
        prefab = robotics.load_bot_prefab_from_file(str(robot))
        links = [prefab.links[index] for index in range(len(prefab.links))]
        joints = [prefab.joints[index] for index in range(len(prefab.joints))]
        children = {index: [] for index in range(len(links))}
        for index, link in enumerate(links[1:], 1):
            children[int(link.parent_link)].append(index)
        physical_root = children[0][0]
        world_position = np.asarray(prefab.world_from_root.translation, dtype=float)
        world_quat = xyzw_to_wxyz(prefab.world_from_root.rotation)
        source_position, source_quat = body_pose(joints[0], links[0])
        root_position, root_quat = compose_pose(
            world_position,
            world_quat,
            source_position,
            source_quat,
        )
        physical_position, physical_quat = body_pose(
            joints[physical_root], links[physical_root]
        )
        root_position, root_quat = compose_pose(
            root_position,
            root_quat,
            physical_position,
            physical_quat,
        )

        root = ET.Element("mujoco", model="pick_up_apple_scene")
        ET.SubElement(root, "compiler", meshdir=".", angle="radian", autolimits="true")
        ET.SubElement(
            root,
            "option",
            timestep="0.002",
            gravity="0 0 -9.81",
            integrator="implicitfast",
            cone="elliptic",
            sdf_iterations="20",
            sdf_initpoints="40",
        )
        asset = ET.SubElement(root, "asset")
        worldbody = ET.SubElement(root, "worldbody")
        ET.SubElement(worldbody, "light", pos="1 -2 4", diffuse=".8 .8 .8")
        add_robot_link(
            worldbody,
            links[physical_root],
            joints[physical_root],
            children,
            links,
            joints,
            exported,
            pose_override=(root_position, root_quat),
        )
        add_contact_exclusions(root, prefab)

        document = json.loads(OBJECTS.read_text())
        for actor in document["actors"]["rigid"]:
            name = str(actor["name"])
            shape = physics.load_shape_from_file(str((OBJECTS.parent / actor["shape"]).resolve()))
            vertices, faces = mesh_arrays(shape)
            if actor.get("isStatic"):
                if actor.get("colliderType") != "BOX":
                    raise NotImplementedError(
                        f"static actor {name}: unsupported collider {actor.get('colliderType')}"
                    )
                # Retain the source mesh as an audited export artifact even
                # though collision uses the authored BOX primitive.
                export_mesh(shape, exported, name)
                lower = np.min(vertices, axis=0)
                upper = np.max(vertices, axis=0)
                ET.SubElement(
                    worldbody,
                    "geom",
                    name=name,
                    type="box",
                    size=fmt((upper - lower) / 2),
                    pos=fmt(np.asarray(actor["translation"], dtype=float) + (lower + upper) / 2),
                    mass="0",
                )
            else:
                if actor.get("colliderType") != "SDF":
                    raise NotImplementedError(
                        f"dynamic actor {name}: unsupported collider {actor.get('colliderType')}"
                    )
                resolution = np.asarray(actor.get("sdf", {}).get("resolutionDelta"), dtype=float)
                if resolution.shape != (3,) or not np.allclose(resolution, [0.0002] * 3):
                    raise ValueError(f"{name}: expected the SuperDex 0.2 mm SDF resolution")
                export_mesh(shape, exported, name)
                body = ET.SubElement(
                    worldbody,
                    "body",
                    name=name,
                    pos=fmt(np.asarray(actor["translation"], dtype=float)),
                )
                ET.SubElement(body, "freejoint", name=f"{name}_root")
                com, inertia, quat = mesh_inertia(vertices, faces, float(actor["mass"]))
                attributes = {
                    "pos": fmt(com),
                    "mass": fmt([float(actor["mass"])]),
                    "diaginertia": fmt(inertia),
                }
                if not np.allclose(quat, [1, 0, 0, 0]):
                    attributes["quat"] = fmt(quat)
                ET.SubElement(body, "inertial", attributes)
                if name == "apple_with_stem":
                    ET.SubElement(
                        body,
                        "geom",
                        name=f"{name}_visual",
                        type="mesh",
                        mesh=name,
                        contype="0",
                        conaffinity="0",
                        mass="0",
                        rgba="0.8 0.05 0.03 1",
                    )
                    ET.SubElement(
                        body,
                        "geom",
                        name=f"{name}_collision",
                        type="sdf",
                        mesh=name,
                        rgba="0 0 0 0",
                    )
                    # Retain the prior component exports for source/hash
                    # auditing; they no longer participate in collision.
                    for component in ("apple", "stem"):
                        export_obj_asset(
                            OBJECTS.parent / f"{component}-collision.obj",
                            exported,
                            f"{component}_collision",
                        )
                else:
                    ET.SubElement(body, "geom", name=f"{name}_collision", type="mesh", mesh=name)

        for name, path in exported.items():
            ET.SubElement(asset, "mesh", name=name, file=path)
        ET.indent(root, space="  ")
        (OUT / "scene.xml").write_text(ET.tostring(root, encoding="unicode") + "\n")


if __name__ == "__main__":
    main()
